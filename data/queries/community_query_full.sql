  UNION ALL SELECT 'twitter-archive/distributedlog'
  UNION ALL SELECT 'apache/incubator-heron'
  UNION ALL SELECT 'google/agera'
  UNION ALL SELECT 'facebookarchive/react-native-fbsdk'
  UNION ALL SELECT 'liyifeng1994/ssm'
  UNION ALL SELECT 'dodola/HotFix'
  UNION ALL SELECT 'hongyangAndroid/FlowLayout'
  UNION ALL SELECT 'Curzibn/Luban'
  UNION ALL SELECT 'laobie/StatusBarUtil'
  UNION ALL SELECT 'vran-dev/PrettyZoo'
  UNION ALL SELECT 'hongyangAndroid/okhttputils'
  UNION ALL SELECT 'facebook/screenshot-tests-for-android'
),

issue_events AS (
  SELECT
    repo.name as repo_name,
    JSON_EXTRACT_SCALAR(payload, '$.action') as action,
    JSON_EXTRACT_SCALAR(payload, '$.issue.number') as issue_number,
    created_at as event_time
  FROM `githubarchive.month.2024*`
  WHERE type IN ('IssuesEvent', 'IssueCommentEvent')
    AND repo.name IN (SELECT repo_name FROM repo_list)
),

pr_events AS (
  SELECT
    repo.name as repo_name,
    type,
    JSON_EXTRACT_SCALAR(payload, '$.action') as action,
    JSON_EXTRACT_SCALAR(payload, '$.pull_request.number') as pr_number,
    created_at as event_time
  FROM `githubarchive.month.2024*`
  WHERE type IN ('PullRequestEvent', 'PullRequestReviewEvent')
    AND repo.name IN (SELECT repo_name FROM repo_list)
),

push_events AS (
  SELECT
    repo.name as repo_name,
    actor.login as contributor,
    CAST(JSON_EXTRACT_SCALAR(payload, '$.size') AS INT64) as commit_count
  FROM `githubarchive.month.2024*`
  WHERE type = 'PushEvent'
    AND repo.name IN (SELECT repo_name FROM repo_list)
),

issue_response AS (
  SELECT
    repo_name,
    issue_number,
    MIN(CASE WHEN action = 'opened' THEN event_time END) as opened_at,
    MIN(CASE WHEN action != 'opened' THEN event_time END) as first_response
  FROM issue_events
  GROUP BY repo_name, issue_number
),

issue_stats AS (
  SELECT
    repo_name,
    APPROX_QUANTILES(TIMESTAMP_DIFF(first_response, opened_at, HOUR)/24.0, 100)[OFFSET(50)] as median_issue_response_days
  FROM issue_response
  WHERE first_response IS NOT NULL AND opened_at IS NOT NULL
  GROUP BY repo_name
),

pr_response AS (
  SELECT
    repo_name,
    pr_number,
    MIN(CASE WHEN type = 'PullRequestEvent' AND action = 'opened' THEN event_time END) as opened_at,
    MIN(CASE WHEN type = 'PullRequestReviewEvent' THEN event_time END) as first_review
  FROM pr_events
  GROUP BY repo_name, pr_number
),

pr_stats AS (
  SELECT
    repo_name,
    APPROX_QUANTILES(TIMESTAMP_DIFF(first_review, opened_at, HOUR)/24.0, 100)[OFFSET(50)] as median_pr_review_days
  FROM pr_response
  WHERE first_review IS NOT NULL AND opened_at IS NOT NULL
  GROUP BY repo_name
),

contributor_stats AS (
  SELECT
    repo_name,
    COUNT(DISTINCT contributor) as unique_contributors,
    SUM(commit_count) as total_commits
  FROM push_events
  GROUP BY repo_name
)

SELECT
  r.repo_name,
  i.median_issue_response_days,
  p.median_pr_review_days,
  c.unique_contributors,
  c.total_commits
FROM repo_list r
LEFT JOIN issue_stats i ON r.repo_name = i.repo_name
LEFT JOIN pr_stats p ON r.repo_name = p.repo_name
LEFT JOIN contributor_stats c ON r.repo_name = c.repo_name
ORDER BY r.repo_name;
